#!/usr/bin/env python3
"""Regenerate the known-good DEFLATE, zlib and gzip vectors.

The streams come from CPython's zlib and gzip modules, which wrap the
reference zlib library. Inputs are synthetic and generated here
deterministically, so nothing in this directory is third-party data.

    python3 crates/format198x-deflate/tests/vectors/generate.py

Writes, next to this script:

- MANIFEST: one line per input: name, length, CRC-32 and Adler-32 as
  Python computes them;
- <name>.l<level>.deflate: raw DEFLATE at levels 0, 1, 6 and 9;
- <name>.l6.zlib, <name>.l9.zlib, <name>.w9.zlib (512-byte window);
- <name>.gz: gzip.compress with mtime 0;
- <name>.full.gz: a member with FTEXT, FEXTRA, FNAME, FCOMMENT and FHCRC;
- multi.gz: two members, "text" then "hello", one after the other;
- text.bin: the text input itself, for a byte-for-byte comparison.
"""

import gzip
import os
import struct
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))


def lcg(seed):
    state = seed
    while True:
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        yield state >> 16


def text(n):
    words = (b"the quick brown fox jumps over lazy dog acorn electron "
             b"spectrum tape snapshot chunk carrier block load save").split()
    rng = lcg(1)
    out = bytearray()
    while len(out) < n:
        out += words[next(rng) % len(words)] + (b"\n" if next(rng) % 9 == 0 else b" ")
    return bytes(out[:n])


def noise(n):
    rng = lcg(2)
    return bytes(next(rng) & 0xFF for _ in range(n))


INPUTS = {
    "empty": b"",
    "hello": b"hello, world\n",
    "bytes": bytes(range(256)) * 4,
    "text": text(20000),
    "noise": noise(4096),
    "zeros": bytes(66000),
    "mixed": text(3000) + noise(1000) + bytes(5000) + text(3000),
}


def raw(data, level):
    c = zlib.compressobj(level, zlib.DEFLATED, -15)
    return c.compress(data) + c.flush()


def zlib_window(data, wbits):
    c = zlib.compressobj(6, zlib.DEFLATED, wbits)
    return c.compress(data) + c.flush()


def full_gzip(data):
    flags = 0x01 | 0x02 | 0x04 | 0x08 | 0x10
    header = b"\x1f\x8b\x08" + bytes([flags]) + struct.pack("<I", 0x5F5E1000)
    header += b"\x02\x03"
    extra = b"F8\x04\x00test"
    header += struct.pack("<H", len(extra)) + extra
    header += b"vector.bin\x00" + b"generated by generate.py\x00"
    header += struct.pack("<H", zlib.crc32(header) & 0xFFFF)
    return header + raw(data, 9) + struct.pack("<II", zlib.crc32(data), len(data) & 0xFFFFFFFF)


def write(name, data):
    with open(os.path.join(HERE, name), "wb") as f:
        f.write(data)


def main():
    manifest = []
    for name, data in INPUTS.items():
        manifest.append(f"{name} {len(data)} {zlib.crc32(data):08x} {zlib.adler32(data):08x}")
        for level in (0, 1, 6, 9):
            write(f"{name}.l{level}.deflate", raw(data, level))
        write(f"{name}.l6.zlib", zlib.compress(data, 6))
        write(f"{name}.l9.zlib", zlib.compress(data, 9))
        write(f"{name}.w9.zlib", zlib_window(data, 9))
        write(f"{name}.gz", gzip.compress(data, 6, mtime=0))
        write(f"{name}.full.gz", full_gzip(data))
    write("multi.gz", gzip.compress(INPUTS["text"], mtime=0) + gzip.compress(INPUTS["hello"], mtime=0))
    write("text.bin", INPUTS["text"])
    write("MANIFEST", ("\n".join(manifest) + "\n").encode())


if __name__ == "__main__":
    main()
