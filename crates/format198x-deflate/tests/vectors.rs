//! Decode streams written by the reference zlib, through CPython.
//!
//! `vectors/generate.py` wrote every file here; see it for what each one
//! holds. The manifest gives each input's length and checksums as Python
//! computed them, so these tests check the decoded data against zlib's
//! own figures, not against this crate's.

use format198x_deflate::{Error, Options, adler32, crc32, gzip, inflate, zlib};
use std::path::PathBuf;

struct Expected {
    name: String,
    len: usize,
    crc: u32,
    adler: u32,
}

fn dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/vectors")
}

fn read(name: &str) -> Vec<u8> {
    let path = dir().join(name);
    std::fs::read(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

fn manifest() -> Vec<Expected> {
    String::from_utf8(read("MANIFEST"))
        .expect("utf-8")
        .lines()
        .map(|line| {
            let f: Vec<&str> = line.split_whitespace().collect();
            Expected {
                name: f[0].to_owned(),
                len: f[1].parse().expect("length"),
                crc: u32::from_str_radix(f[2], 16).expect("crc"),
                adler: u32::from_str_radix(f[3], 16).expect("adler"),
            }
        })
        .collect()
}

fn check(e: &Expected, what: &str, data: &[u8]) {
    assert_eq!(data.len(), e.len, "{what}: length");
    assert_eq!(crc32(data), e.crc, "{what}: CRC-32");
    assert_eq!(adler32(data), e.adler, "{what}: Adler-32");
}

#[test]
fn raw_streams_at_every_level() {
    for e in manifest() {
        for level in [0, 1, 6, 9] {
            let name = format!("{}.l{level}.deflate", e.name);
            let out = inflate(&read(&name)).unwrap_or_else(|err| panic!("{name}: {err}"));
            check(&e, &name, &out);
        }
    }
}

#[test]
fn zlib_streams_including_a_small_window() {
    for e in manifest() {
        for kind in ["l6", "l9", "w9"] {
            let name = format!("{}.{kind}.zlib", e.name);
            let out = zlib::decode(&read(&name)).unwrap_or_else(|err| panic!("{name}: {err}"));
            check(&e, &name, &out);
        }
    }
}

#[test]
fn gzip_members_and_every_header_field() {
    for e in manifest() {
        let name = format!("{}.gz", e.name);
        let member = gzip::decode(&read(&name)).unwrap_or_else(|err| panic!("{name}: {err}"));
        check(&e, &name, &member.data);
        assert_eq!(member.header.mtime, 0);
        assert_eq!(member.header.name, None);

        let name = format!("{}.full.gz", e.name);
        let member = gzip::decode(&read(&name)).unwrap_or_else(|err| panic!("{name}: {err}"));
        check(&e, &name, &member.data);
        let h = &member.header;
        assert!(h.text && h.header_crc);
        assert_eq!((h.mtime, h.extra_flags, h.os), (0x5F5E_1000, 2, 3));
        assert_eq!(h.extra.as_deref(), Some(&b"F8\x04\x00test"[..]));
        assert_eq!(h.name.as_deref(), Some(&b"vector.bin"[..]));
        assert_eq!(h.comment.as_deref(), Some(&b"generated by generate.py"[..]));
    }
}

#[test]
fn a_two_member_file_joins() {
    let text = read("text.bin");
    let member = gzip::decode(&read("multi.gz")).expect("decodes");
    assert_eq!(&member.data[..text.len()], &text[..]);
    assert_eq!(&member.data[text.len()..], b"hello, world\n");
    let members = gzip::decode_members(&read("multi.gz"), &Options::DEFAULT).expect("decodes");
    assert_eq!(members.len(), 2);
}

#[test]
fn the_text_matches_byte_for_byte() {
    let text = read("text.bin");
    assert_eq!(zlib::decode(&read("text.l9.zlib")).expect("decodes"), text);
}

#[test]
fn an_output_limit_stops_a_large_stream() {
    let opts = Options::default().max_output(1000);
    assert_eq!(
        zlib::decode_with(&read("zeros.l9.zlib"), &opts),
        Err(Error::OutputLimit { limit: 1000 })
    );
    let opts = Options::default().max_output(66_000);
    assert_eq!(
        zlib::decode_with(&read("zeros.l9.zlib"), &opts).map(|d| d.len()),
        Ok(66_000)
    );
}

#[test]
fn every_truncation_is_an_error() {
    for name in [
        "text.l6.zlib",
        "mixed.l9.zlib",
        "hello.full.gz",
        "noise.w9.zlib",
    ] {
        let data = read(name);
        for cut in 0..data.len() {
            let r = if name.ends_with(".gz") {
                gzip::decode(&data[..cut]).map(|m| m.data)
            } else {
                zlib::decode(&data[..cut])
            };
            assert!(r.is_err(), "{name} cut at {cut} decoded");
        }
    }
}
